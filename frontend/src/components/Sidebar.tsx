export default function DashboardShell({ children }: { children: React.ReactNode }) {
  const pathname = usePathname()
  const router = useRouter()
  const user = useAuthStore(s => s.user)
  const setUser = useAuthStore(s => s.setUser)

  if (!user) return null

  const navItems = NAV_ITEMS[user.role as UserRole] || []
  const roleLabel = user.role.charAt(0).toUpperCase() + user.role.slice(1)

  const handleLogout = () => {
    logout()
    setUser(null)
    router.push('/auth/login')
  }

  return (
    <div className="min-h-screen bg-[#0A1404] flex">
      {/* Desktop Sidebar */}
      <aside className="hidden md:flex md:flex-col w-64 bg-[#16220D] border-r border-[#2A3D18] fixed h-full z-30">
        <div className="p-4 border-b border-[#2A3D18]">
          <div className="flex items-center gap-3">
            <img src="/logo/logo.png" alt="Logo" className="h-10 w-10 object-contain" onError={(e) => { (e.target as HTMLImageElement).style.display = 'none' }} />
            <div>
              <h2 className="text-[#B6E62E] font-bold text-sm">{APP_NAME}</h2>
              <p className="text-[#8DA88D] text-xs">{roleLabel} Panel</p>
            </div>
          </div>
        </div>
        <nav className="flex-1 overflow-y-auto p-3 space-y-1">
          {navItems.map(item => {
            const active = pathname.startsWith(item.href)
            return (
              <button
                key={item.href}
                onClick={() => router.push(item.href)}
                className={`w-full flex items-center gap-3 px-4 py-2.5 rounded-lg text-sm transition ${
                  active
                    ? 'bg-[#B6E62E]/10 text-[#B6E62E] border border-[#B6E62E]/20'
                    : 'text-[#8DA88D] hover:bg-[#1E2D12] hover:text-[#E8F5E9]'
                }`}
              >
                {Icon({ name: item.icon })}
                <span>{item.label}</span>
              </button>
            )
          })}
        </nav>
        <div className="p-3 border-t border-[#2A3D18]">
          <button
            onClick={handleLogout}
            className="w-full flex items-center gap-3 px-4 py-2.5 rounded-lg text-sm text-red-400 hover:bg-red-500/10 transition"
          >
            {Icon({ name: 'LogOut' })}
            <span>Logout</span>
          </button>
        </div>
      </aside>

      {/* Main Content */}
      <main className="flex-1 md:ml-64 pb-20 md:pb-0 min-h-screen">
        {children}
      </main>

      {/* Mobile Bottom Nav */}
      <nav className="md:hidden fixed bottom-0 left-0 right-0 bg-[#16220D] border-t border-[#2A3D18] z-30 px-2 py-1">
        <div className="flex items-center justify-around">
          {navItems.slice(0, 5).map(item => {
            const active = pathname.startsWith(item.href)
            return (
              <button
                key={item.href}
                onClick={() => router.push(item.href)}
                className={`flex flex-col items-center py-1 px-2 rounded-lg transition ${
                  active ? 'text-[#B6E62E]' : 'text-[#8DA88D]'
                }`}
              >
                {Icon({ name: item.icon, className: 'w-5 h-5' })}
                <span className="text-[10px] mt-0.5">{item.label}</span>
              </button>
            )
          })}
        </div>
      </nav>
    </div>
  )
}
